package algo

import (
	"bytes"
	_ "embed"
	"fmt"
	"text/template"
)

// Input holds the values that the installers put into their scripts. The
// scripts put them in single quotes, so they must not contain single quotes.
type Input struct {
	// Arch is the architecture of the host in the names of the release
	// binaries, such as "amd64".
	Arch string
	// KubernetesVersion is the version of the Kubernetes packages without the
	// leading "v", such as "1.36.6".
	KubernetesVersion string
	// KubernetesRepository is the URL of the apt repository for the minor
	// version, such as "https://pkgs.k8s.io/core:/stable:/v1.36/deb/".
	KubernetesRepository string
	// ContainerdVersion is the version of containerd, such as "2.3.7".
	ContainerdVersion string
	// ContainerdReleaseURL is the base URL of the containerd releases without
	// the trailing slash.
	ContainerdReleaseURL string
	// RuncVersion is the version of runc, such as "1.5.2".
	RuncVersion string
	// RuncReleaseURL is the base URL of the runc releases without the
	// trailing slash.
	RuncReleaseURL string
}

// Ubuntu installs Kubernetes on Ubuntu. It installs containerd and runc of the
// given versions from their releases, and the Kubernetes packages from
// KubernetesRepository with apt.
type Ubuntu struct {
	install   string
	uninstall string
}

// generatedMarker is the first line of the configuration files that the
// install script generates, which the uninstall script removes.
const generatedMarker = "# Generated by the installer of cluster-api-provider-bringyourownhost, which removes this file when it uninstalls Kubernetes."

// containerdService is the systemd unit of containerd, which the releases do
// not include. It is containerd.service of the containerd repository at the
// default version of containerd. `make update-containerd-service` updates it,
// and CI checks that it is up to date.
//
//go:embed containerd.service
var containerdService string

// scriptData is the data of the script templates.
type scriptData struct {
	Input
	GeneratedMarker   string
	ContainerdService string
}

// NewUbuntuInstaller returns the installer for Ubuntu.
func NewUbuntuInstaller(input *Input) (*Ubuntu, error) {
	data := &scriptData{
		Input:             *input,
		GeneratedMarker:   generatedMarker,
		ContainerdService: containerdService,
	}
	install, err := render(ubuntuInstall, data)
	if err != nil {
		return nil, err
	}
	uninstall, err := render(ubuntuUninstall, data)
	if err != nil {
		return nil, err
	}
	return &Ubuntu{install: install, uninstall: uninstall}, nil
}

// Install returns the script that installs Kubernetes.
func (u *Ubuntu) Install() string {
	return u.install
}

// Uninstall returns the script that uninstalls Kubernetes.
func (u *Ubuntu) Uninstall() string {
	return u.uninstall
}

// render executes the script template with text/template.
func render(script string, data *scriptData) (string, error) {
	tmpl, err := template.New("script").Option("missingkey=error").Parse(script)
	if err != nil {
		return "", fmt.Errorf("unable to parse the script: %w", err)
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("unable to render the script: %w", err)
	}
	return buf.String(), nil
}

// The scripts run again on the same host when the host is reused or
// Kubernetes is upgraded, so each step must leave the same result when it
// runs more than once.
const (
	ubuntuInstall = `set -euo pipefail
export DEBIAN_FRONTEND=noninteractive

ARCH='{{.Arch}}'
KUBERNETES_VERSION='{{.KubernetesVersion}}'
KUBERNETES_REPOSITORY='{{.KubernetesRepository}}'
CONTAINERD_VERSION='{{.ContainerdVersion}}'
CONTAINERD_RELEASE_URL='{{.ContainerdReleaseURL}}'
RUNC_VERSION='{{.RuncVersion}}'
RUNC_RELEASE_URL='{{.RuncReleaseURL}}'

# Wait for the lock of dpkg, which unattended-upgrades holds after boot.
apt_get() {
	apt-get -o DPkg::Lock::Timeout=600 "$@"
}

tmp=$(mktemp -d)
trap 'rm -rf "${tmp}"' EXIT

# The packages of the OS would replace containerd and runc that this script
# installs, and their versions would change with the updates of the OS. Check
# them before changing the host.
for pkg in containerd containerd.io docker.io runc; do
	if [ "$(dpkg-query -W -f='${db:Status-Status}' "${pkg}" 2>/dev/null)" = installed ]; then
		echo "The package ${pkg} is installed. Remove it, as the installer installs containerd ${CONTAINERD_VERSION} and runc ${RUNC_VERSION} from their releases." >&2
		exit 1
	fi
done

## disable swap
swapoff -a
# Comment out the swap entries with a marker, so that the uninstall script
# restores only them.
if [ -f /etc/fstab ]; then
	sed -ri '/^\s*[^#[:space:]]\S*\s+\S+\s+swap\s/s/^/#byoh-swap# /' /etc/fstab
fi

## load the kernel modules and set the kernel parameters
cat > /etc/modules-load.d/byoh-k8s.conf <<'EOF'
overlay
br_netfilter
EOF
modprobe overlay
modprobe br_netfilter
cat > /etc/sysctl.d/99-byoh-k8s.conf <<'EOF'
net.bridge.bridge-nf-call-iptables  = 1
net.bridge.bridge-nf-call-ip6tables = 1
net.ipv4.ip_forward                 = 1
EOF
# Apply only this file, so that the other settings stay as they are.
sysctl -p /etc/sysctl.d/99-byoh-k8s.conf

apt_get update
apt_get install -y --no-install-recommends curl gpg ca-certificates

## install containerd and runc of the pinned versions from their releases
if [ "$(/usr/local/bin/containerd --version 2>/dev/null | awk '{print $3}')" != "v${CONTAINERD_VERSION}" ]; then
	containerd_tarball="containerd-${CONTAINERD_VERSION}-linux-${ARCH}.tar.gz"
	curl -fsSL -o "${tmp}/${containerd_tarball}" "${CONTAINERD_RELEASE_URL}/v${CONTAINERD_VERSION}/${containerd_tarball}"
	curl -fsSL -o "${tmp}/${containerd_tarball}.sha256sum" "${CONTAINERD_RELEASE_URL}/v${CONTAINERD_VERSION}/${containerd_tarball}.sha256sum"
	(cd "${tmp}" && sha256sum --check --strict "${containerd_tarball}.sha256sum")
	tar -C /usr/local -xzf "${tmp}/${containerd_tarball}"
fi
if [ "$(/usr/local/sbin/runc --version 2>/dev/null | awk 'NR == 1 {print $3}')" != "${RUNC_VERSION}" ]; then
	curl -fsSL -o "${tmp}/runc.${ARCH}" "${RUNC_RELEASE_URL}/v${RUNC_VERSION}/runc.${ARCH}"
	curl -fsSL -o "${tmp}/runc.sha256sum" "${RUNC_RELEASE_URL}/v${RUNC_VERSION}/runc.sha256sum"
	(cd "${tmp}" && grep -E "[ *]runc\.${ARCH}\$" runc.sha256sum | sha256sum --check --strict)
	install -m 755 "${tmp}/runc.${ARCH}" /usr/local/sbin/runc
fi
# The releases do not include the unit, so install the one of the containerd
# repository at the default version of the installer.
mkdir -p /usr/local/lib/systemd/system
cat > /usr/local/lib/systemd/system/containerd.service <<'EOF'
{{.ContainerdService}}EOF
systemctl daemon-reload

## configure containerd
# containerd reads /etc/containerd/conf.d only when /etc/containerd/config.toml
# imports it, which the default configuration does. Generate the default
# configuration when the host does not have the file, and keep the file of the
# host as it is. The uninstall script removes the generated file, so that the
# next install generates it for the version of containerd then.
mkdir -p /etc/containerd/conf.d
if [ ! -e /etc/containerd/config.toml ]; then
	{
		echo '{{.GeneratedMarker}}'
		/usr/local/bin/containerd config default
	} > /etc/containerd/config.toml
fi
cat > /etc/containerd/conf.d/99-byoh.toml <<'EOF'
version = 3

[plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.runc.options]
  SystemdCgroup = true
EOF
systemctl enable containerd
systemctl restart containerd
if ! /usr/local/bin/containerd config dump | grep -q 'SystemdCgroup = true'; then
	echo "containerd does not use the systemd cgroup driver. Make /etc/containerd/config.toml import /etc/containerd/conf.d/*.toml." >&2
	exit 1
fi

## install the Kubernetes packages
mkdir -p -m 755 /etc/apt/keyrings
curl -fsSL "${KUBERNETES_REPOSITORY}Release.key" | gpg --dearmor --yes -o /etc/apt/keyrings/byoh-kubernetes.gpg
cat > /etc/apt/sources.list.d/byoh-kubernetes.sources <<EOF
Types: deb
URIs: ${KUBERNETES_REPOSITORY}
Suites: /
Signed-By: /etc/apt/keyrings/byoh-kubernetes.gpg
EOF
apt_get update
apt-mark unhold kubelet kubeadm kubectl >/dev/null 2>&1 || true
# kubeadm does not depend on cri-tools, but crictl helps to troubleshoot the node.
apt_get install -y --allow-downgrades --allow-change-held-packages \
	"kubelet=${KUBERNETES_VERSION}-*" "kubeadm=${KUBERNETES_VERSION}-*" "kubectl=${KUBERNETES_VERSION}-*" cri-tools
apt-mark hold kubelet kubeadm kubectl
systemctl enable kubelet
# Let crictl connect to containerd without the flags. Keep the file of the host
# as it is.
if [ ! -e /etc/crictl.yaml ]; then
	cat > /etc/crictl.yaml <<'EOF'
{{.GeneratedMarker}}
runtime-endpoint: unix:///run/containerd/containerd.sock
image-endpoint: unix:///run/containerd/containerd.sock
EOF
fi
`

	ubuntuUninstall = `set -euo pipefail
export DEBIAN_FRONTEND=noninteractive

# Wait for the lock of dpkg, which unattended-upgrades holds after boot.
apt_get() {
	apt-get -o DPkg::Lock::Timeout=600 "$@"
}

## remove the pods that are left
# kubeadm reset removes the pods, but only warns when it fails to. containerd
# keeps the containers of the pods running when it stops (KillMode=process),
# so remove them here, and stop when some are left.
crictl_cmd() {
	crictl --runtime-endpoint unix:///run/containerd/containerd.sock "$@"
}
systemctl start containerd
crictl_cmd rmp --all --force
if [ -n "$(crictl_cmd pods --quiet)" ] || [ -n "$(crictl_cmd ps --all --quiet)" ]; then
	echo "Some pods or containers are left after removing all the pods." >&2
	exit 1
fi
systemctl stop containerd
# Match the process name, as the host agent runs this script with "bash -c",
# whose command line has the text of this script.
if pgrep -x containerd-shim >/dev/null; then
	echo "Some containerd shims are still running after stopping containerd." >&2
	exit 1
fi

## remove the Kubernetes packages
apt-mark unhold kubelet kubeadm kubectl >/dev/null 2>&1 || true
apt_get purge -y kubelet kubeadm kubectl kubernetes-cni cri-tools
rm -f /etc/apt/sources.list.d/byoh-kubernetes.sources /etc/apt/keyrings/byoh-kubernetes.gpg
if [ "$(head -n 1 /etc/crictl.yaml 2>/dev/null)" = '{{.GeneratedMarker}}' ]; then
	rm -f /etc/crictl.yaml
fi

## remove containerd, runc and their data
systemctl disable containerd
rm -f /usr/local/lib/systemd/system/containerd.service
systemctl daemon-reload
rm -f /usr/local/bin/containerd /usr/local/bin/containerd-shim-runc-v2 /usr/local/bin/containerd-stress /usr/local/bin/ctr /usr/local/sbin/runc
rm -f /etc/containerd/conf.d/99-byoh.toml
if [ "$(head -n 1 /etc/containerd/config.toml 2>/dev/null)" = '{{.GeneratedMarker}}' ]; then
	rm -f /etc/containerd/config.toml
fi
# Keep the directories when the host has its own files in them.
rmdir /etc/containerd/conf.d /etc/containerd 2>/dev/null || true
# Unmount what containerd left, from the deepest one, before removing its data.
for mount in $(findmnt --raw --noheadings --output TARGET | grep -E '^/(run|var/lib)/containerd(/|$)' | sort -r || true); do
	umount "${mount}"
done
rm -rf /var/lib/containerd /run/containerd /opt/containerd

## remove the kernel modules and the kernel parameters from the boot
rm -f /etc/modules-load.d/byoh-k8s.conf /etc/sysctl.d/99-byoh-k8s.conf

## restore the swap entries that the install script commented out
if [ -f /etc/fstab ]; then
	sed -i 's/^#byoh-swap# //' /etc/fstab
fi
swapon -a
`
)
